/**
 * Explicit Standalone Email Plan → Sites Private Draft orchestration.
 * This is deliberately an injected transaction boundary, not a sender.
 *
 * A new request UID + audience must be durably saved in the local note
 * BEFORE the POST. Unknown HTTP results must NEVER generate a new UID or
 * retry automatically. Remote results require a fresh GET readback before
 * any local 'saved' status can be recorded. Existing drafts use revision CAS.
 */
import {
  createDraftMutation, validDraftSummary, verifyDraftReadback,
  type StandalonePlan, type Audience, type PrivateDraft, type Mutation,
} from './private-draft-contract.ts';

export interface ExplicitDraftSaveIO {
  persistCreateIdentity(requestUid: string, audienceUid: string): Promise<void>;
  getRemoteDraft(uid: string): Promise<unknown>;
  mutateRemote(mutation: Mutation): Promise<unknown>;
  persistVerifiedReceipt(result: PrivateDraft): Promise<void>;
}
export interface ExplicitDraftSaveRequest {
  plan: StandalonePlan;
  selectedAudienceUid: string;
  authorizedAudiences: readonly Audience[];
  /** generated by a cryptographically secure UUID source only on FIRST create */
  newRequestUid?: string;
  io: ExplicitDraftSaveIO;
}
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;

export async function explicitlySavePrivateDraft(request: ExplicitDraftSaveRequest): Promise<PrivateDraft> {
  const {io,selectedAudienceUid,authorizedAudiences} = request;
  const input = request.plan;
  const plan: StandalonePlan = {...input};

  if (!plan.draftUid) {
    // A create attempt must have immutable identity locally before its first POST.
    // Existing UID is ALWAYS reused after an ambiguous response.
    if (!plan.requestUid) {
      if (!request.newRequestUid || !UUID.test(request.newRequestUid)) {
        throw Error('Cryptographic request UID required for first private Draft creation.');
      }
      plan.requestUid = request.newRequestUid.toLowerCase();
    }
  }
  // Validate trusted audience and saved list BEFORE touching the local note.
  const mutation = createDraftMutation(plan,authorizedAudiences,selectedAudienceUid);
  if (!plan.draftUid) {
    await io.persistCreateIdentity(plan.requestUid,selectedAudienceUid);
  } else {
    // Fail closed if the selected server Draft has moved to a new revision.
    const remote = await io.getRemoteDraft(plan.draftUid);
    if (!validDraftSummary(remote) ||
        remote.uid.toLowerCase() !== plan.draftUid.toLowerCase() ||
        remote.revision !== plan.revision ||
        remote.subject.length > 255) {
      throw Error('Private Draft revision changed; review the remote content before editing.');
    }
  }

  // No retry, no send/schedule, no client-provided raw HTML.
  const response = await io.mutateRemote(mutation);
  if (!validDraftSummary(response)) {
    throw Error('Private Draft mutation outcome unknown; inspect server before retrying.');
  }
  const serverDraft = await io.getRemoteDraft(response.uid);
  const verified = verifyDraftReadback(plan,response,serverDraft);
  // A callback may refuse to mark the note saved if it changed while the network
  // request was in flight. Do not interpret this as a reason to retry the POST.
  await io.persistVerifiedReceipt(verified);
  return verified;
}
